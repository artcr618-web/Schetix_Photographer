# openpyxl потерял бы диаграммы книги.
ШАПКА = ['№', 'Наименование', 'ID', 'Тип', 'Определение', 'Описание алгоритма',
         'Формула (пример расчёта)', 'Где используется', 'Решение (временный)',
         'Справочник · для сверки (временный)']


def строки_листа(разделы):
    из = [['01 · ГЛОССАРИЙ — понятия, типы, обозначения'],
          ['Собирается из модель/глоссарий.py вместе с модель/глоссарий.html. '
           'Столбцы «Решение» и «Справочник» временные — удаляются после согласования.'],
          []]
    def служебные():
        из.append(['СЛУЖЕБНЫЕ ПОНЯТИЯ И ОБОЗНАЧЕНИЯ — язык описания книги, '
                   'со справочником не сверяются'])
        for имя_в, пояснение, строки_в in ВНУТРЕННИЕ:
            из.append([имя_в, пояснение])
            из.append(['№', 'Обозначение', 'В книге', 'Определение', 'Где встречается', 'Статус'])
            for н, (об, ид, опр, зн, где_) in enumerate(строки_в, 1):
                из.append([str(н), об, ид, опр, где_, 'согласовано' if зн == 'В' else 'черновик'])
            из.append([])

    for р in разделы:
        из.append([р['имя']])
        из.append(ШАПКА)
        for с in р['строки']:
            свер = f"{с['термин']} — {СПР[с['термин']]}" if с['термин'] else ''
            своё = ОПРЕДЕЛЕНИЯ.get(с['имя'])
            опред = своё[0] if своё else str(с['опис'] or '')
            из.append([str(с['№']), с['имя'], str(с['ид'] or ''), str(с['тип'] or ''),
                       опред, АЛГОРИТМ.get(с['имя'], ''),
                       str(с['знач'] or ''), с['где'], РЕШЕНИЯ.get(с['имя'], ''), свер])
        из.append([])
        if р['имя'].startswith('A ·'): служебные()
    return из


def экр(t):
    return t.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def буква(n):
    s = ''
    while n > 0:
        n, о = divmod(n - 1, 26)
        s = chr(65 + о) + s
    return s


def в_книгу(разделы):
    import zipfile, shutil, re as _re
    книга = КОРЕНЬ + '/Калькулятор_ставки_часа.xlsx'
    shutil.copy(книга, книга + '.до_глоссария')
    строки = строки_листа(разделы)
    ряды = []
    for i, ряд in enumerate(строки, 1):
        яч = ''.join(
            f'<c r="{буква(j)}{i}" t="inlineStr"><is><t xml:space="preserve">'
            f'{экр(str(v))}</t></is></c>'
            for j, v in enumerate(ряд, 1) if str(v) != '')
        ряды.append(f'<row r="{i}">{яч}</row>')
    xml = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
           '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">'
           '<sheetFormatPr defaultRowHeight="15"/>'
           '<cols><col min="1" max="1" width="6" customWidth="1"/>'
           '<col min="2" max="2" width="34" customWidth="1"/>'
           '<col min="3" max="4" width="16" customWidth="1"/>'
           '<col min="5" max="6" width="60" customWidth="1"/>'
           '<col min="7" max="7" width="38" customWidth="1"/>'
           '<col min="8" max="10" width="26" customWidth="1"/></cols>'
           f'<sheetData>{"".join(ряды)}</sheetData></worksheet>')

    with zipfile.ZipFile(книга) as z:
        части = {n: z.read(n) for n in z.namelist()}
        порядок = z.namelist()
    wb = части['xl/workbook.xml'].decode()
    rels = части['xl/_rels/workbook.xml.rels'].decode()
    rid = {}
    for кусок in _re.findall(r'<Relationship\b[^>]*/>', rels):
        i = _re.search(r'Id="([^"]+)"', кусок); t = _re.search(r'Target="([^"]+)"', кусок)
        if i and t: rid[i.group(1)] = t.group(1)
    лист = dict(_re.findall(r'name="([^"]+)"[^>]*r:id="([^"]+)"', wb))['01_Глоссарий']
    цель = rid[лист]
    путь = цель.lstrip('/') if цель.startswith('/') else 'xl/' + цель
    if путь not in части: raise SystemExit('не найден лист в архиве: ' + путь)
    части[путь] = xml.encode()
    with zipfile.ZipFile(книга, 'w', zipfile.ZIP_DEFLATED) as z:
        for имя in порядок:
            z.writestr(имя, части[имя])
    print(f'лист 01_Глоссарий переписан: {len(строки)} строк, {len(ШАПКА)} столбцов')


