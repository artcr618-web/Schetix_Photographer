def разобрать_лист(путь_книги):
    кн = openpyxl.load_workbook(путь_книги, data_only=True)
    ws = кн['01_Глоссарий']
    разделы, текущий = [], None
    for стр in ws.iter_rows(values_only=True):
        а = стр[0]
        if not isinstance(а, str) or not а.strip(): continue
        а = а.strip()
        прочее = [c for c in стр[1:] if c not in (None, '')]
        if re.match(r'^([A-Z]|\d+)\s*·', а) or (not прочее and len(а) < 90):
            текущий = {'имя': а, 'строки': []}
            разделы.append(текущий)
            continue
        if а.lower() in ('наименование', 'термин'): continue
        if текущий is None:
            текущий = {'имя': 'Без раздела', 'строки': []}
            разделы.append(текущий)
        текущий['строки'].append({
            'раздел': текущий['имя'],
            'имя': а,
            'ид': стр[1] if len(стр) > 1 else None,
            'тип': стр[2] if len(стр) > 2 else None,
            'опис': стр[3] if len(стр) > 3 else None,
            'знач': стр[4] if len(стр) > 4 else None,
        })
    return [р for р in разделы if р['строки']]


def разобрать_книгу():
    """Источник — снимок модель/глоссарий_данные.json.

    Лист книги мы сами же переписываем в новую разметку, поэтому читать его
    повторно нельзя: столбцы сдвинутся. Первый разбор берётся из резервной
    копии книги до перестройки и сохраняется в снимок; дальше правим снимок.
    """
    import json as _json, os
    if os.path.exists(ДАННЫЕ):
        return _json.load(open(ДАННЫЕ, encoding='utf-8'))
    исходник = КОРЕНЬ + '/Калькулятор_ставки_часа.xlsx.до_глоссария'
    if not os.path.exists(исходник): исходник = КОРЕНЬ + '/Калькулятор_ставки_часа.xlsx'
    врем = '/tmp/глоссарий_исходник.xlsx'
    import shutil; shutil.copy(исходник, врем)
    разделы = разобрать_лист(врем)
    _json.dump(разделы, open(ДАННЫЕ, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('снимок сохранён:', ДАННЫЕ)
    return разделы


def статус(с):
    т = совпало(с['имя'])
    if т: return 'тождественно', т
    т = ПЕРЕИМЕНОВАТЬ.get(с['имя'])
