def каталог(имя):
    m = _re.search(r'var CAT=\{(.*?)\n\};', _анкета, _re.S)
    f = _re.search(имя + r":\{k:'(\w+)',rows:\[(.*?)\]\}", m.group(1), _re.S)
    вид, тело = f.group(1), f.group(2)
    поз = _re.findall(r"\['((?:[^'\\]|\\.)*)',([\d.]+),([\d.]+)\]", тело)
    расшифровать = lambda t: _re.sub(r'\\u([0-9a-fA-F]{4})', lambda x: chr(int(x.group(1), 16)), t)
    return вид, [(расшифровать(a), float(b), float(c)) for a, b, c in поз]

