def T(cols, rows, имя_в=0, спр=False, связь=None):
    # имя_в=0 — обычные таблицы: № · Код · Наименование · значения
    # имя_в=1 — вводные: № · Код · Блок · Наименование · значения
    if имя_в:
        cg = ('<col class="cnum"><col class="ck"><col class="cb"><col class="cn">'
              + '<col class="cv">'*(len(cols)-2) + '<col>')
        th = '<th>№</th><th>Код</th>' + ''.join(f'<th>{c}</th>' for c in cols) + '<th></th>'
    else:
        cg = ('<col class="cnum"><col class="ck"><col class="cn">'
              + '<col class="cv">'*len(cols) + '<col>')
        th = ('<th>№</th><th>Код</th><th>Наименование</th>'
              + ''.join(f'<th>{c}</th>' for c in cols) + '<th></th>')
    tr, i = '', 0
    ширина = len(cols) + 3
    for r in rows:
        if r[0] == '§':             # информационная строка на всю ширину
            tr += f'<tr class="пояснение"><td></td><td colspan="{ширина - 1}">{r[1]}</td></tr>'
            continue
        i += 1
        r = list(r)
        if спр:                       # ссылка вешается на само наименование
            поз = 2 if имя_в else 1
            чистое = _re.sub(r'<[^>]+>', '', r[поз])
            терм = (связь or {}).get(чистое) or СВЯЗЬ.get(чистое)
            н = СПР_НОМЕР.get(терм)
            if н:
                r[поз] = f'<a class="спр" href="#спр-{н:02d}">{r[поз]}</a>'
        tr += ('<tr><td>' + f'{i:02d}' + '</td>'
               + ''.join(f'<td>{v}</td>' for v in r) + '<td></td></tr>')
    кл = 'rt вв' if имя_в else 'rt'
    return (f'<div class="wrap"><table class="{кл}"><colgroup>{cg}</colgroup>'
            f'<thead><tr>{th}</tr></thead><tbody>{tr}</tbody></table></div>')

