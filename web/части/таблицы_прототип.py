# ---------- Программа лояльности ----------
# Повтор алгоритма из отчёта: фонд скидок делится на три направления —
# скидка за объём, постоянным клиентам, специальные предложения.
import math
def лояльность(dd):
    hp_ = dd['R']/dd['pool'] if dd['pool'] else 0
    hourAt = lambda S: (S*(1+dd['K'])+dd['cl'])*hp_/S
    S = max(round(dd['S'] or 2), 1)
    r100 = lambda x: math.ceil(x/100)*100
    чек = r100(hourAt(S))*S
    фонд = round(dd['discY'])
    ступени = ((0.05, 2, 0.40), (0.07, 4, 0.40), (0.10, 12, 0.20))
    бюдж, цел = фонд*0.45, dd['py']*0.30
    остБ, остЗ = бюдж, цел
    пост = заказы = людей = 0
    строкиСт = []
    for p_, s_, w in ступени:
        ценаКл = s_*чек*p_
        поБ = min(бюдж*w, остБ)/ценаКл if ценаКл else 0
        поЗ = min(цел*w, остЗ)/s_
        n = max(0, math.floor(min(поБ, поЗ)))
        сум = round(n*s_*чек*p_)
        остБ -= сум; остЗ -= n*s_
        пост += сум; заказы += n*s_; людей += n
        строкиСт.append((p_, s_, n, сум))
    if людей == 0:
        p_, s_, w = ступени[0]
        цена = round(s_*чек*p_)
        if цена <= бюдж and s_ <= цел:
            пост, заказы = цена, s_
            строкиСт[0] = (p_, s_, 1, цена)
    r500 = lambda n: max(round(n/500)*500, 500)
    бюджСпец = min(фонд*0.30, max(фонд-пост, 0))
    номиналы = [r500(чек*0.85), r500(чек*0.40), r500(чек*0.25)]
    ост = бюджСпец
    n0 = 1 if ост >= номиналы[0] else 0; ост -= номиналы[0]*n0
    n1 = max(0, math.floor(ост*0.45/номиналы[1])); ост -= номиналы[1]*n1
    n2 = max(0, math.floor(ост/номиналы[2]))
    спец = номиналы[0]*n0 + номиналы[1]*n1 + номиналы[2]*n2
    объём = max(фонд-пост-спец, 0)
    return dict(чек=чек, фонд=фонд, пост=пост, спец=спец, объём=объём,
                заказы=заказы, ступени=строкиСт,
                серт=list(zip(номиналы, [n0, n1, n2])))

