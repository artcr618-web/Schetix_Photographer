#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Работа с отдельным блоком отчёта: вынести → править → вернуть.

    python3 блок.py список          какие блоки есть и что вынесено
    python3 блок.py вынести 03      вырезать блок 03 в свой файл
    python3 блок.py вернуть 03      вставить обратно в каркас
    python3 блок.py собрать 03      пересобрать обвязку файла блока

Блок называется по НОМЕРУ, который виден в отчёте: 01, 02, 03 …
В самой вёрстке у блоков исторические id (card06 у блока 03) —
их менять нельзя, на них завязан CSS. Но файлы и команды работают
по номеру, чтобы не путаться.

ЗАЧЕМ. Править блок прямо в каркасе тяжело: файл на 300 КБ, соседние
блоки мешают, вёрстка съезжает незаметно. Вынесенный блок живёт в
отдельном файле, который открывается как обычная страница — со всеми
стилями и настоящими цифрами.

КАК УСТРОЕН ФАЙЛ БЛОКА. Это полноценный HTML: шапка, весь CSS отчёта,
сам блок между метками, скрипт отчёта. Открываете — видите блок ровно
таким, каким он будет в отчёте.

    <!--БЛОК-НАЧАЛО-->
    <div class="card" id="card06"> ... </div>
    <!--БЛОК-КОНЕЦ-->

Правите ТОЛЬКО между метками. Всё остальное — обвязка для просмотра,
она в отчёт не попадает: собрать.py берёт из файла кусок между метками.

ЦИКЛ РАБОТЫ.
    1. python3 блок.py вынести 03
    2. правите части/03.html между метками, смотрите глазами
    3. python3 собрать.py         — отчёт уже собирается с правками
    4. python3 блок.py вернуть 03 — когда блок утверждён

После «вернуть» блок снова живёт в каркасе. Файл в «части» остаётся:
автоматически из этой папки ничего не удаляется.
"""
import io, os, re, sys

ЗДЕСЬ  = os.path.dirname(os.path.abspath(__file__))
ЧАСТИ  = os.path.join(ЗДЕСЬ, 'части')
КАРКАС = os.path.join(ЧАСТИ, 'каркас.html')
ОТЧЁТ  = os.path.join(ЗДЕСЬ, 'report.html')

НАЧАЛО = '<!--БЛОК-НАЧАЛО-->'
КОНЕЦ  = '<!--БЛОК-КОНЕЦ-->'


def читать(п):
    return io.open(п, encoding='utf-8').read()


def писать(п, s):
    io.open(п, 'w', encoding='utf-8').write(s)


def карта(s):
    """{номер блока: id в вёрстке}. Номер — то, что видно в отчёте,
    id — историческое имя в разметке: у блока 03 это card06."""
    out = {}
    for m in re.finditer(r'<div class="card" id="([\w-]+)"><div class="bn">([^<]*)<', s):
        out[m.group(2).strip()] = m.group(1)
    return out


def в_ид(s, имя):
    """Принимаем и номер («03»), и id («card06»)."""
    к = карта(s)
    if имя in к:
        return к[имя]
    if имя in к.values() or ('<div class="card" id="%s">' % имя) in s:
        return имя
    return None


def найти_блок(s, ид):
    """Границы <div class="card" id="ид"> … </div> с учётом вложенности."""
    метка = '<div class="card" id="%s">' % ид
    if метка not in s:
        return None
    i = s.index(метка)
    гл = 0
    for m in re.finditer(r'<div\b|</div>', s[i:]):
        гл += 1 if m.group(0) == '<div' else -1
        if гл == 0:
            return i, i + m.end()
    return None


def обвязка(блок, ид):
    """Файл блока: настоящие стили и скрипт отчёта вокруг куска разметки."""
    отчёт = читать(ОТЧЁТ)
    стили = ''.join(re.findall(r'<style>[\s\S]*?</style>', отчёт))
    скрипт = ''.join(re.findall(r'<script>[\s\S]*?</script>', отчёт))
    # Скрипт отчёта обращается к элементам всех блоков, а здесь только один:
    # без заглушки render() падает на первом же отсутствующем элементе.
    щит = ('<script>\n'
           '/* На странице один блок, элементов остальных нет. Отдаём для них\n'
           '   невидимую пустышку, иначе скрипт отчёта падает на первом же\n'
           '   обращении и блок остаётся пустым. */\n'
           '(function(){var р=document.getElementById.bind(document);\n'
           'document.getElementById=function(id){return р(id)||'
           '(function(){var e=document.createElement("div");'
           'e.style.display="none";return e})()}})();\n'
           '</script>\n')
    return ('<!DOCTYPE html>\n<html lang="ru"><head><meta charset="utf-8">\n'
            '<meta name="viewport" content="width=device-width,initial-scale=1">\n'
            '<title>Счетикс · блок %s</title>\n</head><body>\n'
            '<!-- Правьте ТОЛЬКО между метками БЛОК-НАЧАЛО и БЛОК-КОНЕЦ.\n'
            '     Всё вокруг — обвязка для просмотра, в отчёт она не идёт.\n'
            '     Отчёт собирается: python3 собрать.py -->\n'
            '<div id="phr-root">\n%s\n<div class="wp">\n'
            '%s\n%s\n%s\n'
            '</div>\n</div>\n%s%s\n</body></html>\n'
            % (ид, стили, НАЧАЛО, блок, КОНЕЦ, щит, скрипт))


# ------------------------------------------------------------------ команды
def список():
    s = читать(КАРКАС)
    к = карта(s)
    вынесены = re.findall(r'<!--БЛОК:([\w-]+)-->', s)
    print('В каркасе (%d):' % len(к))
    for ном in sorted(к, key=lambda x: (not x.isdigit(), x)):
        print('   блок %-6s id %s' % (ном or '—', к[ном]))
    if вынесены:
        print('\nВынесены (%d) — правятся в части/:' % len(вынесены))
        for имя in вынесены:
            п = os.path.join(ЧАСТИ, имя + '.html')
            print('   блок %-6s части/%s.html %s'
                  % (имя, имя, '' if os.path.exists(п) else '— ФАЙЛА НЕТ'))
    else:
        print('\nВынесенных нет.')
    return 0


def вынести(имя):
    s = читать(КАРКАС)
    if '<!--БЛОК:%s-->' % имя in s:
        print('блок %s уже вынесен.' % имя)
        return 1
    ид = в_ид(s, имя)
    if not ид:
        print('нет блока %s. Посмотрите: python3 блок.py список' % имя)
        return 1
    гр = найти_блок(s, ид)
    if not гр:
        print('нет блока %s в каркасе' % имя)
        return 1
    i, j = гр
    писать(os.path.join(ЧАСТИ, имя + '.html'), обвязка(s[i:j], имя))
    писать(КАРКАС, s[:i] + '<!--БЛОК:%s-->' % имя + s[j:])
    print('блок %s вынесен → части/%s.html' % (имя, имя))
    print('правьте между метками, потом: python3 собрать.py')
    return 0


def вернуть(ид):
    п = os.path.join(ЧАСТИ, ид + '.html')
    if not os.path.exists(п):
        print('нет файла ' + п)
        return 1
    ф = читать(п)
    if НАЧАЛО not in ф or КОНЕЦ not in ф:
        print('в файле нет меток БЛОК-НАЧАЛО / БЛОК-КОНЕЦ')
        return 1
    блок = ф.split(НАЧАЛО, 1)[1].split(КОНЕЦ, 1)[0].strip('\n')
    s = читать(КАРКАС)
    if '<!--БЛОК:%s-->' % ид not in s:
        print('в каркасе нет метки <!--БЛОК:%s-->' % ид)
        return 1
    писать(КАРКАС, s.replace('<!--БЛОК:%s-->' % ид, блок))
    # Файл блока НЕ удаляем: из папки «части» ничего не пропадает само.
    # Он остаётся как последняя рабочая версия блока. Чистить — только руками.
    print('%s возвращён в каркас. Файл части/%s.html оставлен.' % (ид, ид))
    print('пересоберите: python3 собрать.py')
    return 0


def пересобрать(ид):
    """Обновить обвязку файла блока: стили и скрипт берутся из свежего отчёта.
    Нужно, если менялась палитра или общий CSS, а блок вынесен давно."""
    п = os.path.join(ЧАСТИ, ид + '.html')
    if not os.path.exists(п):
        print('нет файла ' + п)
        return 1
    ф = читать(п)
    блок = ф.split(НАЧАЛО, 1)[1].split(КОНЕЦ, 1)[0].strip('\n')
    писать(п, обвязка(блок, ид))
    print('обвязка %s обновлена из report.html' % ид)
    return 0


def главное():
    арг = sys.argv[1:]
    if not арг:
        print(__doc__)
        return 1
    к = арг[0]
    if к == 'список':
        return список()
    if len(арг) < 2:
        print('укажите блок, например: python3 блок.py %s card06' % к)
        return 1
    ид = арг[1]
    if к == 'вынести':
        return вынести(ид)
    if к == 'вернуть':
        return вернуть(ид)
    if к == 'собрать':
        return пересобрать(ид)
    print('неизвестная команда:', к)
    print(__doc__)
    return 1


if __name__ == '__main__':
    sys.exit(главное())
