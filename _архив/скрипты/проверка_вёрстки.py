#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Проверка вёрстки: ловит класс ошибок «поехала разметка после правки».

    python3 проверка_вёрстки.py файл.html
    python3 проверка_вёрстки.py файл.html --было прежний.html

Работает на любом HTML: и на report.html, и на макетах в «части».
Пять проверок:

  1. баланс скобок в CSS и тегов в HTML
  2. переменные, которые используются, но не объявлены
  3. незакрытые медиазапросы
  4. дубли селекторов: позднее правило перебивает раннее по тем же свойствам
  5. сверка с прежней версией — что пропало и у чего изменились значения

Пятая — главная. Она показывает, что правка задела то, чего не просили.

Код возврата: 0 — чисто, 1 — есть находки.
"""
import io, os, re, sys

VOID = {'br','img','input','meta','link','hr','source','area','col','embed','track','wbr',
        'circle','path','rect','polygon','line','ellipse','stop','use','polyline',
        'feDropShadow','animate','image'}

# свойства, расхождение по которым и даёт «поехавшие интервалы»
ВАЖНЫЕ = ('margin','padding','font-size','line-height','text-align','gap',
          'grid-template-columns','display','width','height','border-radius',
          'position','background','color','border','box-shadow','letter-spacing')


def читать(п):
    return io.open(п, encoding='utf-8').read()


def без_кода(s):
    """Глушит <script>/<style>/комментарии, сохраняя длину: внутри JS
    встречается разметка в строках, её нельзя считать тегами."""
    def глушь(m):
        return m.group(1) + re.sub(r'[^\n]', ' ', m.group(2)) + m.group(3)
    s = re.sub(r'(<script[^>]*>)([\s\S]*?)(</script>)', глушь, s)
    s = re.sub(r'(<style[^>]*>)([\s\S]*?)(</style>)', глушь, s)
    s = re.sub(r'<!--[\s\S]*?-->', lambda m: re.sub(r'[^\n]', ' ', m.group(0)), s)
    return s


def весь_css(s):
    return '\n'.join(re.findall(r'<style[^>]*>([\s\S]*?)</style>', s))


# ---------------------------------------------------------------- 1. скобки
def проверка_скобок(s):
    беды = []
    css = весь_css(s)
    раз = css.count('{') - css.count('}')
    if раз:
        беды.append('CSS: дисбаланс скобок %+d' % раз)

    чистый = без_кода(s)
    стек = []
    for m in re.finditer(r'<(/?)([a-zA-Z][\w-]*)([^>]*?)(/?)>', чистый):
        зак, имя, само = m.group(1), m.group(2).lower(), m.group(4)
        if имя in VOID or само == '/':
            continue
        if зак:
            if стек and стек[-1][0] == имя:
                стек.pop()
            else:
                беды.append('ТЕГИ: лишний </%s> строка %d'
                            % (имя, чистый[:m.start()].count('\n') + 1))
        else:
            стек.append((имя, m.start()))
    for имя, поз in стек[:5]:
        беды.append('ТЕГИ: не закрыт <%s> строка %d'
                    % (имя, чистый[:поз].count('\n') + 1))
    return беды


# ------------------------------------------------------------ 2. переменные
def проверка_переменных(s):
    беды = []
    использованы = set(re.findall(r'var\((--[\w-]+)', s))
    объявлены = set(re.findall(r'(--[\w-]+)\s*:', s))
    # переменные вида --exb задаются инлайн в style="" — это законно
    инлайн = set(re.findall(r'style="[^"]*?(--[\w-]+)\s*:', s))
    # var(--x, запасное) — объявление не обязательно, значение есть всегда
    с_запасным = set(re.findall(r'var\((--[\w-]+)\s*,', s))
    # setProperty('--x', ...) из JS — переменная появляется во время работы
    из_js = set(re.findall(r"setProperty\(\s*['\"](--[\w-]+)", s))
    нет = использованы - объявлены - инлайн - с_запасным - из_js
    if нет:
        беды.append('ПАЛИТРА: не объявлены ' + ', '.join(sorted(нет)))
    циклы = re.findall(r'(--[\w-]+)\s*:\s*var\(\1\)', s)
    if циклы:
        беды.append('ПАЛИТРА: ссылка на себя — ' + ', '.join(sorted(set(циклы))))
    return беды


# --------------------------------------------------------- 3. медиазапросы
def проверка_медиа(s):
    """Незакрытый @media проглатывает весь CSS ниже: правила есть,
    но не применяются. Скобочный баланс это ловит не всегда —
    лишняя } где-то ещё может его скомпенсировать."""
    беды = []
    css = весь_css(s)
    for m in re.finditer(r'@media[^{]*\{', css):
        глуб, i = 1, m.end()
        while i < len(css) and глуб:
            if css[i] == '{': глуб += 1
            elif css[i] == '}': глуб -= 1
            i += 1
        if глуб:
            беды.append('МЕДИА: не закрыт %s строка %d'
                        % (m.group(0)[:44], css[:m.start()].count('\n') + 1))
        else:
            # закрылся, но проглотил слишком много — признак потерянной }
            тело = css[m.end():i]
            if тело.count('{') > 40:
                беды.append('МЕДИА: %s охватывает %d правил — вероятно потеряна }'
                            % (m.group(0)[:40], тело.count('{')))
    return беды


# ---------------------------------------------------------------- разбор CSS
def правила(css):
    """{селектор: {свойство: значение}} — по последнему объявлению.
    Медиазапросы разбираются вместе с их условием в ключе."""
    out = {}
    css = re.sub(r'/\*[\s\S]*?\*/', '', css)
    for усл, тело in разделить_медиа(css):
        for m in re.finditer(r'([^{}]+)\{([^{}]*)\}', тело):
            сел = ' '.join(m.group(1).split())
            if сел.startswith('@'):
                continue
            ключ = (усл + ' ' if усл else '') + сел
            св = out.setdefault(ключ, {})
            for пара in m.group(2).split(';'):
                if ':' in пара:
                    п, з = пара.split(':', 1)
                    св[п.strip()] = ' '.join(з.split())
    return out


def разделить_медиа(css):
    """[(условие, тело), ...] — верхний уровень идёт с пустым условием."""
    куски, верх, i = [], [], 0
    while i < len(css):
        m = re.compile(r'@media[^{]*\{').search(css, i)
        if not m:
            верх.append(css[i:]); break
        верх.append(css[i:m.start()])
        глуб, j = 1, m.end()
        while j < len(css) and глуб:
            if css[j] == '{': глуб += 1
            elif css[j] == '}': глуб -= 1
            j += 1
        куски.append((' '.join(m.group(0)[:-1].split()), css[m.end():j - 1]))
        i = j
    return [('', ''.join(верх))] + куски


# ------------------------------------------------------------------ 4. дубли
def проверка_дублей(s):
    """Два правила с одним селектором и общим свойством: то, что ниже,
    молча перебивает верхнее. Так .note{text-align:center} перебивал
    .note.warn и текст уведомлений уезжал по центру."""
    беды = []
    for усл, тело in разделить_медиа(re.sub(r'/\*[\s\S]*?\*/', '', весь_css(s))):
        видели = {}
        for m in re.finditer(r'([^{}]+)\{([^{}]*)\}', тело):
            сел = ' '.join(m.group(1).split())
            if сел.startswith('@'):
                continue
            свойства = {п.split(':', 1)[0].strip()
                        for п in m.group(2).split(';') if ':' in п}
            if сел in видели:
                общие = (видели[сел] & свойства) & set(ВАЖНЫЕ)
                if общие:
                    беды.append('ДУБЛЬ: %s%s — «%s» задано дважды, побеждает нижнее'
                                % (усл + ' ' if усл else '', сел,
                                   ', '.join(sorted(общие))))
            видели[сел] = видели.get(сел, set()) | свойства
    return беды


# ------------------------------------------------------------- 5. сверка
def сверка(старый, новый):
    """Что изменилось против прежней версии. Показывает ровно то, что
    правка задела — включая соседние элементы, которых не просили."""
    a, b = правила(весь_css(старый)), правила(весь_css(новый))
    вести = []

    пропали = sorted(set(a) - set(b))
    if пропали:
        вести.append('  пропали правила: ' + ', '.join(пропали[:8])
                     + (' и ещё %d' % (len(пропали) - 8) if len(пропали) > 8 else ''))
    новые = sorted(set(b) - set(a))
    if новые:
        вести.append('  добавились: ' + ', '.join(новые[:8])
                     + (' и ещё %d' % (len(новые) - 8) if len(новые) > 8 else ''))

    for сел in sorted(set(a) & set(b)):
        for св in sorted(set(a[сел]) | set(b[сел])):
            if св not in ВАЖНЫЕ and not св.startswith(tuple(ВАЖНЫЕ)):
                continue
            бы, ст = a[сел].get(св), b[сел].get(св)
            if бы != ст:
                вести.append('  %s · %s: %s → %s'
                             % (сел, св, бы or '—', ст or '—'))
    return вести


# -------------------------------------------------------------------- ход
def главное():
    арг = [x for x in sys.argv[1:] if not x.startswith('--')]
    if not арг:
        print(__doc__)
        return 1
    файл = арг[0]
    if not os.path.exists(файл):
        print('нет файла:', файл)
        return 1
    s = читать(файл)

    беды = (проверка_скобок(s) + проверка_переменных(s)
            + проверка_медиа(s) + проверка_дублей(s))

    print('проверяю', os.path.basename(файл))
    if беды:
        for б in беды:
            print('  ✗', б)
    else:
        print('  ✓ скобки · переменные · медиазапросы · дубли селекторов')

    если_было = None
    if '--было' in sys.argv:
        i = sys.argv.index('--было')
        если_было = sys.argv[i + 1] if i + 1 < len(sys.argv) else None
    if если_было and os.path.exists(если_было):
        вести = сверка(читать(если_было), s)
        print('\nсверка с', os.path.basename(если_было) + ':')
        if вести:
            for в in вести[:40]:
                print(в)
            if len(вести) > 40:
                print('  ... и ещё %d изменений' % (len(вести) - 40))
        else:
            print('  изменений в оформлении нет ✓')

    return 1 if беды else 0


if __name__ == '__main__':
    sys.exit(главное())
