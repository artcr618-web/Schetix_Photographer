#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ЗАДАЧИ СЧЁТИКСА — одна связка вместо разрозненных списков.

Устройство:
  schetix/ЗАДАЧИ/З-001_короткое_имя.md   — по документу на задачу
  schetix/ЗАДАЧИ/_архив/                 — закрытые задачи уезжают сюда
  schetix/ЗАДАЧИ/РЕЕСТР.md               — общая таблица, СОБИРАЕТСЯ АВТОМАТОМ

Источник правды — сами файлы задач. Реестр никогда не правим руками:
он пересобирается из шапок этих файлов, поэтому разойтись не может.

Шапка задачи (первые строки файла):
    # З-003 · Перенести таблицы в отчёт
    Приоритет: P0
    Статус: ▶ в работе
    Создана: 18.08.2026
    Обновлена: 18.08.2026
    Файлы: web/report.html, web/части/таблицы_прототип.py

Команды:
  python3 задачи.py список                     что открыто, по приоритетам
  python3 задачи.py новая "Название" P0         завести задачу
  python3 задачи.py запись З-003 "что решили"   датированная запись + дата в шапке
  python3 задачи.py статус З-003 работе|начато  сменить статус
  python3 задачи.py готово З-003                закрыть и убрать в архив
  python3 задачи.py реестр                      пересобрать РЕЕСТР.md
"""
import sys, os, re, io, shutil, datetime

КОРЕНЬ = '/home/user/schetix'
ПАПКА = os.path.join(КОРЕНЬ, 'ЗАДАЧИ')
АРХИВ = os.path.join(ПАПКА, '_архив')
РЕЕСТР = os.path.join(ПАПКА, 'РЕЕСТР.md')
СТАТУСЫ = {'начато': '☐ не начато', 'работе': '▶ в работе',
           'готово': '✔ готово', 'отказ': '× отказались'}
МЕСЯЦЫ = ['января','февраля','марта','апреля','мая','июня',
          'июля','августа','сентября','октября','ноября','декабря']

def сегодня():
    д = datetime.date.today()
    return f'{д.day:02d}.{д.month:02d}.{д.year}'

def файлы(включая_архив=True):
    с = []
    for п in ([ПАПКА, АРХИВ] if включая_архив else [ПАПКА]):
        if not os.path.isdir(п): continue
        с += [os.path.join(п, и) for и in sorted(os.listdir(п))
              if и.startswith('З-') and и.endswith('.md')]
    return с

def шапка(путь):
    т = io.open(путь, encoding='utf-8').read()
    д = {'путь': путь, 'имя': os.path.basename(путь)}
    m = re.match(r'#\s*(З-\d+)\s*·\s*(.+)', т.split('\n')[0])
    д['код'], д['название'] = (m.group(1), m.group(2).strip()) if m else ('?', д['имя'])
    for поле in ('Приоритет', 'Статус', 'Создана', 'Обновлена', 'Файлы'):
        m = re.search(r'^%s:\s*(.+)$' % поле, т, re.M)
        д[поле.lower()] = m.group(1).strip() if m else ''
    д['в_архиве'] = os.path.dirname(путь) == АРХИВ
    return д

def собрать_реестр():
    зз = [шапка(п) for п in файлы()]
    зз.sort(key=lambda з: з['код'])
    откр = [з for з in зз if not з['статус'].startswith(('✔', '×'))]
    закр = [з for з in зз if з['статус'].startswith(('✔', '×'))]

    def таблица(строки, архив=False):
        т = ('| Код | Задача | Приоритет | Статус | Документ | Обновлена |\n'
             '|---|---|---|---|---|---|\n')
        for з in строки:
            путь = ('_архив/' if з['в_архиве'] else '') + з['имя']
            т += (f"| {з['код']} | {з['название']} | {з['приоритет']} | "
                  f"{з['статус']} | [{з['имя']}]({путь}) | {з['обновлена']} |\n")
        return т

    текст = ['# РЕЕСТР ЗАДАЧ',
             '',
             '**Собирается автоматически** командой `python3 ДОКУМЕНТАЦИЯ/4_инструменты/задачи.py реестр`.',
             'Руками не правим — правим сами документы задач.',
             '',
             f'Обновлено: {сегодня()} · открытых: {len(откр)} · закрытых: {len(закр)}',
             '']
    for п in ('P0', 'P1', 'P2'):
        часть = [з for з in откр if з['приоритет'] == п]
        if часть:
            подпись = {'P0': 'P0 — без этого не публикуем',
                       'P1': 'P1 — в первый месяц',
                       'P2': 'P2 — когда дойдут руки'}[п]
            текст += [f'## {подпись}', '', таблица(часть)]
    прочее = [з for з in откр if з['приоритет'] not in ('P0', 'P1', 'P2')]
    if прочее:
        текст += ['## Без приоритета', '', таблица(прочее)]
    if закр:
        текст += ['## Закрытые — лежат в `_архив/`', '', таблица(закр, True)]
    io.open(РЕЕСТР, 'w', encoding='utf-8').write('\n'.join(текст))
    print(f'реестр пересобран: открытых {len(откр)}, закрытых {len(закр)}')

def найти(код):
    for п in файлы():
        if os.path.basename(п).startswith(код):
            return п
    raise SystemExit(f'задача {код} не найдена')

def новая(название, приоритет='P1', зачем='', шаги=None, файлы_=''):
    os.makedirs(ПАПКА, exist_ok=True)
    номера = [int(re.match(r'З-(\d+)', os.path.basename(п)).group(1)) for п in файлы()]
    код = f'З-{max(номера) + 1 if номера else 1:03d}'
    корот = re.sub(r'[^\wа-яА-ЯёЁ]+', '_', название.lower())[:40].strip('_')
    путь = os.path.join(ПАПКА, f'{код}_{корот}.md')
    шаги = шаги or ['']
    т = (f'# {код} · {название}\n'
         f'Приоритет: {приоритет}\n'
         f'Статус: ☐ не начато\n'
         f'Создана: {сегодня()}\n'
         f'Обновлена: {сегодня()}\n'
         f'Файлы: {файлы_}\n\n'
         f'## Зачем\n\n{зачем or "—"}\n\n'
         f'## Что сделать\n\n'
         + ''.join(f'- [ ] {ш}\n' for ш in шаги) +
         f'\n## Решения и правки\n\n'
         f'- {сегодня()} — задача заведена.\n')
    io.open(путь, 'w', encoding='utf-8').write(т)
    print('создана:', os.path.basename(путь))
    return путь

def обновить_дату(путь):
    т = io.open(путь, encoding='utf-8').read()
    т = re.sub(r'^Обновлена:.*$', f'Обновлена: {сегодня()}', т, count=1, flags=re.M)
    io.open(путь, 'w', encoding='utf-8').write(т)

def запись(код, текст):
    путь = найти(код)
    т = io.open(путь, encoding='utf-8').read().rstrip('\n')
    т += f'\n- {сегодня()} — {текст}\n'
    io.open(путь, 'w', encoding='utf-8').write(т)
    обновить_дату(путь)
    print(f'{код}: запись добавлена')

def статус(код, ключ):
    путь = найти(код)
    т = io.open(путь, encoding='utf-8').read()
    т = re.sub(r'^Статус:.*$', f'Статус: {СТАТУСЫ[ключ]}', т, count=1, flags=re.M)
    io.open(путь, 'w', encoding='utf-8').write(т)
    обновить_дату(путь)
    print(f'{код}: {СТАТУСЫ[ключ]}')

def готово(код):
    путь = найти(код)
    статус(код, 'готово')
    запись(код, 'задача закрыта, документ убран в архив.')
    os.makedirs(АРХИВ, exist_ok=True)
    shutil.move(путь, os.path.join(АРХИВ, os.path.basename(путь)))
    print(f'{код}: в архиве')

def список():
    зз = [шапка(п) for п in файлы(включая_архив=False)]
    зз.sort(key=lambda з: (з['приоритет'], з['код']))
    for п in ('P0', 'P1', 'P2'):
        часть = [з for з in зз if з['приоритет'] == п and not з['статус'].startswith(('✔', '×'))]
        if не_пусто := часть:
            print(f'\n▶ {п}')
            for з in не_пусто:
                print(f"  {з['статус'][:1]} {з['код']}  {з['название']}"
                      + (f"   → {з['имя']}" if з['статус'].startswith('▶') else ''))
    print()

if __name__ == '__main__':
    к = sys.argv[1] if len(sys.argv) > 1 else 'список'
    if к == 'список':  список()
    elif к == 'реестр': собрать_реестр()
    elif к == 'новая':  новая(sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else 'P1'); собрать_реестр()
    elif к == 'запись': запись(sys.argv[2], sys.argv[3]); собрать_реестр()
    elif к == 'статус': статус(sys.argv[2], sys.argv[3]); собрать_реестр()
    elif к == 'готово': готово(sys.argv[2]); собрать_реестр()
    else: print(__doc__)
