#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Пересобирает все автоматически получаемые листы чистой книги.

После любого изменения HTML обновляет карту значений, интерфейс, тексты и CSS,
контракт отчёта, программу лояльности и 00_Читать, затем пересчитывает книгу.
"""
from pathlib import Path
import subprocess,sys
ROOT=Path(__file__).resolve().parents[1]
scripts=[
 'справочник_в_отчёт.py',
 'мигрировать_каталоги_в_чистую.py',
 'собрать_интерфейс.py',
 'собрать_тексты.py',
 'собрать_css.py',
 'синхронизировать_названия_calc.py',
 'синхронизировать_рабочее_место.py',
 'синхронизировать_обучение.py',
 'синхронизировать_сайт.py',
 'синхронизировать_финансовое_ядро_чистой.py',
 'собрать_полный_отчёт.py',
 'собрать_программу_лояльности.py',
 'собрать_00_читать.py',
 'пересчитать_чистую_книгу.py',
]
for name in scripts:
    path=ROOT/'Инструменты'/name
    print('▶',name)
    subprocess.check_call([sys.executable,str(path)])
print('Карта чистой книги пересобрана полностью')
