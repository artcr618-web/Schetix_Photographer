#!/usr/bin/env node
/* Замеряет вёрстку настоящего браузера, а не догадывается о ней.

   Зачем: jsdom (на нём сидят проверки разметки) не считает ни сетку, ни
   размеры текста — он отдаёт нули. Пиксельные меры — зазор между блоками,
   положение разделительной черты, число строк заголовка, высота страницы —
   снимаются только из headless-браузера. Инструмент нужен в двух местах
   работы: перед правкой отступов (чтобы иметь числа) и после (чтобы
   сверить, что стало ровно так, как задумано, а не «на глаз сошлось»).
   Визуальная проверка скриншотом — дополнение, а не замена чисел.

   Запуск:
     node Инструменты/замерить_вёрстку.js .
     node Инструменты/замерить_вёрстку.js . --страница Веб/preview.html
     node Инструменты/замерить_вёрстку.js . --ширины 1024,390
     node Инструменты/замерить_вёрстку.js . --сохранить /tmp/было.json
     node Инструменты/замерить_вёрстку.js . --сравнить /tmp/было.json
     node Инструменты/замерить_вёрстку.js . --ряд "#phc-root .benefits-grid" --скриншоты
     node Инструменты/замерить_вёрстку.js . --мера плашка=#phc-root .benefit --допуск 1
     node Инструменты/замерить_вёрстку.js . --скриншоты --плотность 2   # снимок ретины
     node Инструменты/замерить_вёрстку.js . --раскрыть --ряд "#c_FormPromoTime .stage-list"   # мерить внутри «Подробнее»

   Меры по умолчанию — ряд плашек лендинга calc.html. Свой ряд задают через
   --ряд (по нему считаются зазоры между детьми плашки и снимаются
   скриншоты), дополнительные меры — повторами --мера имя=селектор.

   Страницу читаем по file://, а не через локальный сервер: у собранного
   calc.html нет <meta charset>, http-сервер отдаёт его в cp1252, вместо
   кириллицы в заголовках arrives mojibake, переносы строк получаются
   другими — и все замеры врут.

   Скриншоты пишутся ВНЕ репозитория (по умолчанию ../Скриншоты), чтобы не
   раздувать рабочую папку: посмотрел — папку вычистил.

   Зависимость: npm ci в папке Инструменты (нужен puppeteer, он же при
   установке тянет браузер). Браузеру нужны системные библиотеки; на голом
   Debian/Ubuntu их ставят один раз: apt-get install -y --no-install-recommends
   libnss3 libnspr4 libatk1.0-0t64 libatk-bridge2.0-0t64 libatspi2.0-0t64
   libxkbcommon0 libasound2t64 libxdamage1 (имена с t64 — для Debian 13;
   на Debian 12 без суффикса). Без них запуск падает с 'error while loading
   shared libraries' — это не дефект вёрстки. Код выхода: 0 — расхождений за допуск нет
   (или эталон не задан), 1 — есть, 2/3 — инструмент не смог запуститься. */
const fs = require('fs'), path = require('path');
let puppeteer;
try { puppeteer = require('puppeteer'); }
catch (e) {
  console.error('Не установлен puppeteer. Выполните npm ci в папке Инструменты.');
  process.exit(3);
}

/* ---------- командная строка: позиция = корень, --флаг[=значение] ---------- */
const флаги = {}, повторы = [];
{
  const argv = process.argv.slice(2);
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--мера' || a === '-m') { if (argv[i + 1]) { повторы.push(argv[++i]); } continue; }
    if (a.startsWith('--')) {
      const тело = a.slice(2), n = тело.indexOf('=');
      if (n > 0) { флаги[тело.slice(0, n)] = тело.slice(n + 1); continue; }
      const следующий = argv[i + 1];
      if (следующий !== undefined && !следующий.startsWith('--')) { флаги[тело] = следующий; i++; }
      else флаги[тело] = true;
      continue;
    }
    if (!флаги.корень) флаги.корень = a;
  }
}

const ROOT = path.resolve(флаги.корень || path.join(__dirname, '..'));
const СТРАНИЦА = path.resolve(ROOT, флаги.страница || 'Веб/calc.html');
const МЕТКА = path.basename(СТРАНИЦА).replace(/\.[a-z0-9]+$/i, '');
const ВИДЫ = String(флаги.ширины || '1440,1024,620,390').split(',')
  .map(n => parseInt(String(n).trim(), 10)).filter(Boolean);
const РЯД = String(флаги.ряд || '#phc-root .benefits-grid');
const ДОПУСК = Number(флаги.допуск !== undefined ? флаги.допуск : 1);
/* плотность пикселей: 1 — обычный экран, 2 — ретина. Нужна, чтобы увидеть,
   дробную долю пикселя браузер «прилипает» к строке растра или нет */
const ПЛОТНОСТЬ = Number(флаги.плотность !== undefined ? флаги.плотность : 1);
const ПАПКА_СКРИНШОТОВ = path.resolve(typeof флаги.скриншоты === 'string'
  ? флаги.скриншоты : path.join(ROOT, '..', 'Скриншоты'));
const МЕРЫ = (повторы.length ? повторы : [
  'плашки=#phc-root .benefit',
  'заголовки=#phc-root .benefit-title',
  'ссылки=#phc-root .benefit-demo',
]).map(строка => {
  const n = строка.indexOf('=');
  return n > 0 ? { имя: строка.slice(0, n), селектор: строка.slice(n + 1) }
    : { имя: строка, селектор: строка };
});

/* ------------------------- снимок страницы в браузере -------------------------
   Возвращает CSS-пиксели, округлённые до 0.1: мельче сравнивать бессмысленно. */
const СНИМОК = (имена, селекторы, рядСелектор) => {
  const д = в => Math.round(в * 10) / 10;
  const бокс = el => {
    const b = el.getBoundingClientRect();
    return { x: д(b.x), y: д(b.y), w: д(b.width), h: д(b.height), низ: д(b.bottom), право: д(b.right) };
  };
  const rectы = el => {
    const d = document.createRange();
    d.selectNodeContents(el);
    return Array.from(d.getClientRects()).filter(b => b.width > 0.5 && b.height > 0.5);
  };
  /* Текст — объединение rect'ов: <br> делит логическую строку на два rect'а,
     поэтому число rect'ов и число строк — разные величины, обе и показываем. */
  const текст = el => {
    const л = rectы(el);
    if (!л.length) return null;
    const верх = Math.min.apply(null, л.map(b => b.top));
    const низ = Math.max.apply(null, л.map(b => b.bottom));
    const верхи = Array.from(new Set(л.map(b => Math.round(верх0(b)))));
    function верх0(b) { return b.top; }
    const cs = getComputedStyle(el);
    return { верх: д(верх), низ: д(низ), rectов: л.length, строк: верхи.length,
      высоты: л.map(b => д(b.height)),
      шаг: л.length > 1 ? д((низ - л[0].top) / (л.length - 1)) : 0,
      кегль: д(parseFloat(cs.fontSize) || 0), межстрочное: д(parseFloat(cs.lineHeight) || 0) };
  };
  const имя = el => (typeof el.className === 'string' && el.className.trim() ? el.className.trim().split(/\s+/)[0] : el.tagName.toLowerCase());
  const измерить = el => {
    if (!el) return null;
    const cs = getComputedStyle(el), б = бокс(el), т = текст(el);
    return { класс: имя(el), бокс: б, текст: т, начертание: (cs.fontWeight || '') + '/' + (cs.fontStyle || '') + '/' + (cs.fontFamily || '').split(',')[0].replace(/['\"]/g, ''),
      нижняяЧерта: д(б.низ - (parseFloat(cs.borderBottomWidth) || 0) / 2),
      толщинаЧерты: д(parseFloat(cs.borderBottomWidth) || 0),
      поля: { в: д(parseFloat(cs.marginTop) || 0), н: д(parseFloat(cs.marginBottom) || 0) },
      отступы: { в: д(parseFloat(cs.paddingTop) || 0), н: д(parseFloat(cs.paddingBottom) || 0) } };
  };
  /* Соседство ищем не «по документу», а по геометрии: предыдущим считается
     тот элемент, который целиком выше и пересекается по горизонтали. Иначе в
     ряду из трёх плашек у второй «предыдущей» оказалась бы первая, а зазор
     между ними горизонтальный и в высоте смысла не имеет. */
  const над = (a, b) => a.низ <= b.y + 1 && Math.max(a.x, b.x) < Math.min(a.право, b.право);
  const сЗазорами = список => {
    const элементы = список.map(измерить);
    элементы.forEach((э, n) => {
      if (!э) return;
      э.зазор = null; э.зазорТекстом = null;
      for (let i = n - 1; i >= 0; i--) {
        const пред = элементы[i];
        if (пред && над(пред.бокс, э.бокс)) {
          э.зазор = д(э.бокс.y - пред.бокс.низ);
          э.зазорТекстом = э.текст ? д(э.текст.верх - пред.бокс.низ) : null;
          break;
        }
      }
    });
    /* Строка ряда = элементы, чьи вертикальные интервалы пересекаются. Черту
       сравниваем только внутри строки: на мобильном плашки стоят столбцом, и
       расхождение вышло бы в сотни пикселей вместо настоящих долей пикселя. */
    const пересекаются = (a, b) => Math.min(a.низ, b.низ) - Math.max(a.y, b.y) > 1;
    const группы = [];
    элементы.forEach((э, n) => {
      if (!э) return;
      const группа = группы.find(г => г.some(i => пересекаются(элементы[i].бокс, э.бокс)));
      if (группа) группа.push(n); else группы.push([n]);
    });
    группы.forEach(г => г.forEach(i => {
      элементы[i].вСтроке = г.length;
      элементы[i].чертаОтПервой = д(элементы[i].нижняяЧерта - элементы[г[0]].нижняяЧерта);
    }));
    return элементы;
  };
  const данные = {};
  имена.forEach((имя, n) => { данные[имя] = сЗазорами(Array.from(document.querySelectorAll(селекторы[n]))); });
  const кореньРяда = document.querySelector(рядСелектор);
  const ряд = !кореньРяда ? null : {
    селектор: рядСелектор, бокс: бокс(кореньРяда),
    плашки: Array.from(кореньРяда.children).map(плашка => ({
      класс: имя(плашка), бокс: бокс(плашка),
      зазоры: сЗазорами(Array.from(плашка.children)).slice(1).map((э, i) => ({
        между: имя(плашка.children[i]) + ' → ' + (э ? э.класс : '?'),
        боксКБоксу: э.зазор, текстКБоксу: э.зазорТекстом, черта: э.нижняяЧерта })),
    })),
  };
  return { файл: decodeURIComponent(document.location.pathname.split('/').pop()),
    высотаСтраницы: Math.round(document.documentElement.scrollHeight),
    ширинаКлиента: document.documentElement.clientWidth,
    горизонтальныйСдвиг: document.documentElement.scrollWidth > document.documentElement.clientWidth + 1,
    ряд, данные };
};

const ч = в => (в === null || в === undefined || Number.isNaN(Number(в))) ? '—' : String(Math.round(Number(в) * 10) / 10);
const разброс = значения => значения.length ? Math.max.apply(null, значения) - Math.min.apply(null, значения) : 0;

async function main() {
  if (!fs.existsSync(СТРАНИЦА)) { console.error('Нет страницы: ' + СТРАНИЦА); process.exit(2); }
  if (флаги.скриншоты) fs.mkdirSync(ПАПКА_СКРИНШОТОВ, { recursive: true });
  const снято = {};
  const браузер = await puppeteer.launch({
    headless: 'shell',
    args: ['--no-sandbox', '--disable-setuid-sandbox', '--disable-dev-shm-usage',
      '--hide-scrollbars', '--force-device-scale-factor=' + ПЛОТНОСТЬ, '--font-render-hinting=none'],
  });
  try {
    const стр = await браузер.newPage();
    for (const ширина of ВИДЫ) {
      await стр.setViewport({ width: ширина, height: 1000, deviceScaleFactor: ПЛОТНОСТЬ });
      await стр.goto('file://' + СТРАНИЦА, { waitUntil: 'load', timeout: 60000 });
      await стр.evaluateHandle('document.fonts ? document.fonts.ready : Promise.resolve()').catch(() => {});
      if (флаги.раскрыть) {
        /* свёрнутые «Подробнее» закрыты по умолчанию, и их содержимое имело бы нулевые
           размеры — для замеров списка внутри свёрнутых блоков их надо раскрыть */
        const селектор = typeof флаги.раскрыть === 'string' ? флаги.раскрыть : 'details';
        await стр.evaluate((с) => document.querySelectorAll(с).forEach(д => { д.open = true; }), селектор);
      }
      снято[ширина] = await стр.evaluate(СНИМОК, МЕРЫ.map(м => м.имя), МЕРЫ.map(м => м.селектор), РЯД);
      if (флаги.скриншоты) {
        const рукоятка = await стр.$(РЯД);
        if (рукоятка) {
          const хвост = (ПЛОТНОСТЬ !== 1 ? '@' + ПЛОТНОСТЬ + 'x' : '');
          const файл = path.join(ПАПКА_СКРИНШОТОВ, МЕТКА + '-' + ширина + хвост + '.png');
          await рукоятка.screenshot({ path: файл });
          снято[ширина].скриншот = файл;
        }
        if (флаги.полный_кадр) {
          const полный = path.join(ПАПКА_СКРИНШОТОВ, МЕТКА + '-' + ширина + хвост + '-страница.png');
          await стр.screenshot({ path: полный, fullPage: true });
          снято[ширина].скриншотСтраницы = полный;
        }
      }
    }
  } finally { await браузер.close(); }

  if (флаги.json) console.log(JSON.stringify(снято));

  for (const ширина of ВИДЫ) {
    const с = снято[ширина];
    console.log('\n=== ' + ширина + 'px · ' + с.файл + ' · высота страницы ' + с.высотаСтраницы
      + (с.горизонтальныйСдвиг ? ' · есть горизонтальный сдвиг' : '') + ' ===');
    for (const м of МЕРЫ) {
      const элементы = (с.данные || {})[м.имя] || [];
      if (!элементы.length) { console.log('  ' + м.имя + ': пусто по «' + м.селектор + '»'); continue; }
      элементы.forEach((э, n) => {
        if (!э) return;
        const т = э.текст;
        console.log('  ' + м.имя + ' ' + (n + 1) + ': ' + ч(э.бокс.w) + '×' + ч(э.бокс.h) + ' @ '
          + ч(э.бокс.x) + ',' + ч(э.бокс.y) + ' · черта y=' + ч(э.нижняяЧерта) + ' (толщ ' + ч(э.толщинаЧерты) + ')'
          + ' · зазор ' + ч(э.зазор) + (э.зазорТекстом === null ? '' : ', текстом ' + ч(э.зазорТекстом))
          + ' · поля ' + ч(э.поля.в) + '/' + ч(э.поля.н) + ' · шрифт ' + э.начертание
          + (т ? ' · rectов ' + т.rectов + ', строк ' + т.строк + ' [' + т.высоты.join(',') + '], шаг ' + ч(т.шаг)
            + ', кегль ' + ч(т.кегль) + '/' + ч(т.межстрочное) : ''));
      });
      /* Разъезд считаем только внутри строки ряда — то, ради чего обычно и мерят */
      const вСтроке = элементы.filter(э => э && э.вСтроке > 1);
      const сводка = (метка, получить, набор) => {
        const значения = (набор || элементы).map(получить).filter(v => typeof v === 'number');
        if (значения.length < 2) return;
        const р = разброс(значения);
        console.log('  → ' + метка + ' [' + значения.map(ч).join(' | ') + '] разброс ' + ч(р) + 'px'
          + (р > ДОПУСК ? '  ← разъезд за допуск ' + ч(ДОПУСК) + 'px' : ' (в допуске)'));
      };
      сводка(м.имя + ' · черта внутри строки', э => э && э.чертаОтПервой, вСтроке);
      сводка(м.имя + ' · высота', э => э && э.бокс.h);
      сводка(м.имя + ' · зазор текстом', э => э && э.зазорТекстом);
    }
    if (с.ряд) {
      const первый = [];
      с.ряд.плашки.forEach((п, n) => {
        const з = (п.зазоры || []).map(з => з.между + ' ' + ч(з.текстКБоксу) + 'px (боксом ' + ч(з.боксКБоксу) + ')');
        console.log('  плашка ' + (n + 1) + ' зазоры: ' + (з.join(' · ') || 'нет детей'));
        if (п.зазоры && п.зазоры.length) первый.push(п.зазоры[0].текстКБоксу);
      });
      const числа = первый.filter(v => typeof v === 'number');
      if (числа.length > 1) {
        const р = разброс(числа);
        console.log('  → ряд · первый зазор [' + числа.map(ч).join(' | ') + '] разброс ' + ч(р) + 'px'
          + (р > ДОПУСК ? '  ← разъезд' : ''));
      }
    }
    if (с.скриншот) console.log('  скриншот: ' + с.скриншот + (с.скриншотСтраницы ? ' · ' + с.скриншотСтраницы : ''));
  }

  if (флаги.сохранить) {
    const путь = path.resolve(String(флаги.сохранить));
    fs.mkdirSync(path.dirname(путь), { recursive: true });
    fs.writeFileSync(путь, JSON.stringify(снято, null, 1));
    console.log('\nмеры сохранены: ' + путь);
  }

  let расхождений = 0;
  if (флаги.сравнить) {
    const эталон = JSON.parse(fs.readFileSync(path.resolve(String(флаги.сравнить)), 'utf8'));
    console.log('\n=== сравнение с эталоном · ' + path.resolve(String(флаги.сравнить)) + ' · допуск ' + ч(ДОПУСК) + 'px ===');
    const метка = (метка, было, стало, дельта) =>
      метка + ': ' + ч(было) + ' → ' + ч(стало) + ' (' + (дельта > 0 ? '+' : '') + ч(дельта) + ')';
    for (const ширина of ВИДЫ) {
      const а = эталон[ширина], б = снято[ширина];
      if (!а || !б) { console.log('  ' + ширина + 'px: в эталоне такого вида нет — пропускаю'); continue; }
      const список = [];
      const сверить = (меткаСравнения, было, стало) => {
        if (typeof было !== 'number' || typeof стало !== 'number') return;
        const дельта = стало - было;
        if (Math.abs(дельта) > ДОПУСК) список.push(метка(меткаСравнения, было, стало, дельта));
      };
      сверить('высота страницы', а.высотаСтраницы, б.высотаСтраницы);
      for (const м of МЕРЫ) {
        const было = (а.данные || {})[м.имя] || [], стало = (б.данные || {})[м.имя] || [];
        if (было.length !== стало.length) { список.push(м.имя + ': элементов было ' + было.length + ', стало ' + стало.length); continue; }
        стало.forEach((э, n) => {
          const п = было[n];
          if (!э || !п) return;
          const номер = м.имя + ' ' + (n + 1);
          сверить(номер + ' ширина', п.бокс.w, э.бокс.w);
          сверить(номер + ' высота', п.бокс.h, э.бокс.h);
          сверить(номер + ' y', п.бокс.y, э.бокс.y);
          сверить(номер + ' черта', п.нижняяЧерта, э.нижняяЧерта);
          сверить(номер + ' черта в строке', п.чертаОтПервой, э.чертаОтПервой);
          сверить(номер + ' зазор', п.зазор, э.зазор);
          сверить(номер + ' зазор текстом', п.зазорТекстом, э.зазорТекстом);
          if (п.текст && э.текст) сверить(номер + ' rectов', п.текст.rectов, э.текст.rectов);
        });
      }
      расхождений += список.length;
      console.log('  ' + ширина + 'px: ' + (список.length ? 'расхождения' : 'в допуске'));
      список.forEach(строка => console.log('    · ' + строка));
    }
    console.log(расхождений ? '\nЗА ДОПУСК: ' + расхождений + ' расхождений'
      : '\nза допуск ничего не вышло — снимок совпал с эталоном');
  }
  process.exit(расхождений ? 1 : 0);
}
main().catch(e => { console.error('сбой:', e && e.message ? e.message : e); process.exit(2); });
