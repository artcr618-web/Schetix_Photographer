#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ПРОВЕРКА ЦЕЛОСТНОСТИ ПРОЕКТА СЧЁТИКС — единая точка входа.

Запуск из корня проекта:
    python3 Инструменты/проверить.py [корень]

Запускает зелёный гейт действующего веб-контура calc → report / price
(`проверить_активный_контур.py`). Зелёный результат означает исправность
исполняемых страниц и их контракта данных.

28.09.2026, решение владельца: исторический аудит `--legacy` (книга, архив,
PDF, каркас и старые контракты) удалён вместе со скриптами синхронизации
книги — он опирался на удалённые скрипты и устаревшую книгу. Флаги
`--active` и `--legacy` принимаются для совместимости и ничего не меняют.
"""
import os
import subprocess
import sys

АРГУМЕНТЫ = [a for a in sys.argv[1:] if a not in ('--active', '--legacy')]
ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
КОРЕНЬ = АРГУМЕНТЫ[0] if АРГУМЕНТЫ else os.path.dirname(ЗДЕСЬ)

if '--legacy' in sys.argv[1:]:
    print('▶ исторический аудит удалён 28.09 — выполняется активный гейт')

активный = os.path.join(ЗДЕСЬ, 'проверить_активный_контур.py')
raise SystemExit(subprocess.run([sys.executable, активный, КОРЕНЬ]).returncode)
