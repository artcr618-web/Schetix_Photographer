# -*- coding: utf-8 -*-
"""Сверяет Excel-глоссарий, пользовательский СПРАВОЧНИК и лист «Состав».

Источник понятий и определений — `01_Глоссарий` книги.
`СПРАВОЧНИК` — пользовательская часть глоссария, опубликованная в отчёте.

Запуск из любой папки:

    python3 Инструменты/сверить_глоссарий.py
    python3 Инструменты/сверить_глоссарий.py /путь/к/Schetix_Photographer

Инструмент ничего не изменяет. Он выводит расхождения и всегда завершает работу
обычно: найденные отличия являются списком для разбора с владельцем, а не поводом
самостоятельно переписывать глоссарий.
"""
from pathlib import Path
from contextlib import redirect_stdout
import importlib.util
import io
import re
import sys
import unicodedata

import openpyxl


def найти_корень():
    if len(sys.argv) > 1:
        p = Path(sys.argv[1]).expanduser().resolve()
        if (p / 'Книга' / 'Калькулятор_ставки_часа.xlsx').exists():
            return p
        raise SystemExit(f'Не найдена чистая книга в указанном корне: {p}')
    for p in [Path(__file__).resolve().parent, *Path(__file__).resolve().parents]:
        if (p / 'Книга' / 'Калькулятор_ставки_часа.xlsx').exists():
            return p
    raise SystemExit('Не удалось определить корень проекта по чистой книге')


def ключ(значение):
    с = unicodedata.normalize('NFKC', str(значение or '')).lower().replace('ё', 'е')
    с = re.sub(r'\s+', ' ', с).strip()
    return с


def текст(значение):
    """Нормализация определения: абзацы не должны создавать ложное расхождение."""
    return re.sub(r'\s+', ' ', str(значение or '')).strip()


def загрузить_справочник(корень):
    путь = корень / 'Инструменты' / 'таблицы_прототип.py'
    spec = importlib.util.spec_from_file_location('таблицы_прототип', путь)
    модуль = importlib.util.module_from_spec(spec)
    # Генератор при импорте печатает служебное «ok»; сверке оно не относится.
    with redirect_stdout(io.StringIO()):
        try:
            spec.loader.exec_module(модуль)
        except SystemExit:
            pass
    return модуль.СПРАВОЧНИК


def строки_глоссария(лист):
    результат = []
    # Фактическая структура: A № · B Наименование · D Назначение · F Определение.
    for r in range(2, лист.max_row + 1):
        имя = лист.cell(r, 2).value
        if not isinstance(имя, str) or not имя.strip():
            continue
        результат.append({
            'строка': r,
            'номер': лист.cell(r, 1).value,
            'имя': имя.strip(),
            'назначение': str(лист.cell(r, 4).value or '').strip(),
            'определение': str(лист.cell(r, 6).value or '').strip(),
        })
    return результат


def печать_списка(заголовок, строки):
    print('\n' + '=' * 78)
    print(f'{заголовок}: {len(строки)}')
    for строка in строки:
        print('  ·', строка)


корень = найти_корень()
книга = openpyxl.load_workbook(
    корень / 'Книга' / 'Калькулятор_ставки_часа.xlsx', data_only=True)
справочник = загрузить_справочник(корень)

глоссарий = строки_глоссария(книга['01_Глоссарий'])
по_ключу = {ключ(x['имя']): x for x in глоссарий}
спр_по_ключу = {ключ(имя): (имя, определение)
                 for имя, определение in справочник.items()}

# 1. Любое опубликованное понятие обязано существовать в источнике правды.
нет_в_глоссарии = []
for k, (имя, _) in спр_по_ключу.items():
    if k not in по_ключу:
        нет_в_глоссарии.append(имя)

# 2. Опубликованное определение должно дословно совпадать по смысловому тексту.
разные_определения = []
for k, (имя, определение) in спр_по_ключу.items():
    if k in по_ключу and текст(определение) != текст(по_ключу[k]['определение']):
        разные_определения.append(
            f'{имя} (глоссарий: строка {по_ключу[k]["строка"]}, № {по_ключу[k]["номер"] or "—"})')

# 3. Пользовательские записи глоссария, пока не опубликованные в справочнике.
# Это информационный список: публикацию каждого понятия решает владелец.
не_опубликованы = []
for запись in глоссарий:
    if запись['назначение'] == 'user' and ключ(запись['имя']) not in спр_по_ключу:
        не_опубликованы.append(
            f'{запись["имя"]} (строка {запись["строка"]}, № {запись["номер"] or "—"})')

# 4. На листе «Состав» все наименования и составные части должны быть понятиями
# глоссария. Колонка A — технический ID, её не проверяем.
состав_без_глоссария = []
if 'Состав' in книга.sheetnames:
    лист = книга['Состав']
    for r in range(5, лист.max_row + 1):
        for c in range(2, лист.max_column + 1):
            значение = лист.cell(r, c).value
            if not isinstance(значение, str) or not значение.strip():
                continue
            if ключ(значение) not in по_ключу:
                состав_без_глоссария.append(
                    f'{лист.cell(r, c).coordinate}: {значение.strip()}')

print(f'Корень: {корень}')
print(f'Глоссарий: {len(глоссарий)} записей')
print(f'Пользовательский справочник: {len(справочник)} записей')

печать_списка('Справочник: нет понятия в глоссарии', нет_в_глоссарии)
печать_списка('Справочник: определение отличается от глоссария', разные_определения)
печать_списка('Глоссарий user: пока не опубликовано в справочнике', не_опубликованы)
печать_списка('Лист «Состав»: понятие отсутствует в глоссарии', состав_без_глоссария)

print('\n' + '=' * 78)
print('Сверка завершена. Файлы не изменялись.')
