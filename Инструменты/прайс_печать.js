    /* Ромб со скруглёнными вершинами как path (эквивалент rect 10.1×10.1 rx 1.9,
       повёрнутого на 45°). */
    function ромб(cx, cy, цвет){
      var r = 7.14, k = 1.35;   /* полудиагональ; k — срез вершины под скругление */
      function f(x){ return (+x).toFixed(2); }
      var d = 'M' + f(cx - k) + ' ' + f(cy - r + k) +
        'Q' + f(cx) + ' ' + f(cy - r) + ' ' + f(cx + k) + ' ' + f(cy - r + k) +
        'L' + f(cx + r - k) + ' ' + f(cy - k) +
        'Q' + f(cx + r) + ' ' + f(cy) + ' ' + f(cx + r - k) + ' ' + f(cy + k) +
        'L' + f(cx + k) + ' ' + f(cy + r - k) +
        'Q' + f(cx) + ' ' + f(cy + r) + ' ' + f(cx - k) + ' ' + f(cy + r - k) +
        'L' + f(cx - r + k) + ' ' + f(cy + k) +
        'Q' + f(cx - r) + ' ' + f(cy) + ' ' + f(cx - r + k) + ' ' + f(cy - k) + 'Z';
      return '<path d="' + d + '" fill="' + цвет + '"/>';
    }
