        var ст = столбцыТаблицы(таблица);
        var естьСрочно = ст.indexOf('fast') >= 0;
        var естьСрок = ст.indexOf('ready') >= 0 && строки.some(function(tr){ var п = tr.querySelector('.cr'); return п && дниГотовности(п.value) > 0; });
        /* Столбцы по очереди (решение владельца 06.09): Услуга · Цена ·
           [Готовность] · [Срочный заказ] — без пропусков, каждый следующий
           занимает следующий столбец эталонной сетки. */
        var естьКол = ст.indexOf('qty') >= 0;
        шапка = [шапкаПоКлючу(таблица, 'th0', 'Услуга')];
        if(естьКол) шапка.push(шапкаПоКлючу(таблица, 'th2', 'Кол-во'));
        шапка.push(шапкаПоКлючу(таблица, 'th3', 'Цена'));
        if(естьСрок) шапка.push(шапкаПоКлючу(таблица, 'th5', 'Готовность, дней'));
        if(естьСрочно) шапка.push(шапкаПоКлючу(таблица, 'th4', 'Срочный заказ'));
