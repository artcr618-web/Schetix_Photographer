    function клонПечБаннера(){
      var обёртка = КОРЕНЬ.querySelector('.pc-hero-wrap');
      if(!обёртка) return null;
      var к = обёртка.cloneNode(true);
      к.className = 'pc-hero-wrap pv-клон ph-view';
      к.removeAttribute('data-block-id'); к.removeAttribute('data-block-name');
      var пол = {};                                    /* id полей — до их удаления */
      [].forEach.call(к.querySelectorAll('[id]'), function(э){ пол[э.id] = э; });
      [].forEach.call(к.querySelectorAll('.ph-tools,.ph-c-x,button'),
        function(э){ э.remove(); });
      /* Поля обложки печатаются как есть — вместе с временными значениями
         (правило владельца 07.09: поле с подсказкой тоже выводится, как на
         экране). Пустое поле получает текст своей подсказки; ссылкой такое
         поле не становится — вымышленного телефона/почты быть не должно. */
      var временные = [];
      [].forEach.call(к.querySelectorAll('.ph-kicker,.ph-name,.ph-c-val'), function(э){
        var т = э.textContent.replace(/\s+/g, ' ').trim();
        var подсказка = (э.getAttribute('data-placeholder') || '').trim();
        if(!т){ э.textContent = подсказка; временные.push(э); }
        else if(т.toLowerCase() === подсказка.toLowerCase()) временные.push(э);
      });
      [].forEach.call(к.querySelectorAll('[data-tip],[data-placeholder],[contenteditable],' +
          '[spellcheck],[aria-pressed],[aria-label],[role],[tabindex],[data-удалить]'), function(э){
        ['data-tip','data-placeholder','contenteditable','spellcheck','aria-pressed','aria-label',
         'role','tabindex','data-удалить'].forEach(function(а){ э.removeAttribute(а); });
      });
      [].forEach.call(к.querySelectorAll('[id]'), function(э){ э.removeAttribute('id'); });
      var фон = к.querySelector('img.ph-bg');
      if(фон && !фон.getAttribute('src')) фон.remove();   /* фото нет — не тянем пустой img */
      /* Контакты → кликабельные ссылки, классы (и вёрстка строки) сохраняются. */
      function вСсылку(э, href){
        if(!э || !к.contains(э) || !href) return;
        var a = document.createElement('a');
        a.className = э.className + ' ph-c-link';
        a.setAttribute('href', href);
        while(э.firstChild) a.appendChild(э.firstChild);
        э.parentNode.replaceChild(a, э);
      }
      /* Клон ещё не в document — isConnected не годится, проверяем через
         contains: удалённый элемент из клона выпадает. */
      function чisto(э){ return э && к.contains(э) && временные.indexOf(э) < 0 ? э.textContent.trim() : ''; }
      var тел = чisto(пол.phPhone), почта = чisto(пол.phEmail), сайт = чisto(пол.phSite);
      вСсылку(пол.phPhone, тел ? 'tel:' + тел.replace(/[^\d+]/g, '') : '');
      вСсылку(пол.phEmail, почта ? 'mailto:' + почта : '');
      var сайтHref = сайт ? (/^https?:\/\//i.test(сайт) ? сайт : 'https://' + сайт.replace(/^\/+/, '')) : '';
      вСсылку(пол.phSite, сайтHref);
      return к;
    }
